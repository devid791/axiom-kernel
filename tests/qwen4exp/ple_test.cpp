    bool ok = true;
    ok = test_checkpoint_golden_metadata() && ok;
    ok = test_transactional_ids_eos_and_conv() && ok;
    ok = test_fail_closed_contract() && ok;
    ok = test_committed_ring_wrap_and_move() && ok;
